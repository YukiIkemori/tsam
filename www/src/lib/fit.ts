// 大きな欧文の見出しを、枠の幅いっぱいに組むための寸法（太さの試作）。
//
// 見出しはふだん極細（200）。コーラルの o（メンター）が座った一語だけが極太（800）に膨らみ、
// 膨らみきったときに、ちょうど枠の左右に届く。その大きさを CSS に渡すのがここ。
//   .fit { font-size: calc(100cqw / var(--fit)) }   … --fit は「800 で組んだときの幅（em）」
//
// 下の表は Jost Variable の 800 の送り幅（1em あたり。2026-11-27 に Chromium で実測）。
// 字詰め（カーニング）は数えない。数えると少し狭くなる語と、少し広くなる語（Glossary・Story など +0.03em）があるので、
// 3% の余裕を見ている。字間は 800 のとき -0.04em（global.css の .display と同じ値）。
const A: Record<string, number> = {
  '0': 0.681, '1': 0.527, '2': 0.682, '3': 0.643, '4': 0.732, '5': 0.669, '6': 0.697, '7': 0.626, '8': 0.651, '9': 0.697,
  a: 0.556, b: 0.631, c: 0.498, d: 0.631, e: 0.591, f: 0.361, g: 0.622, h: 0.581, i: 0.281, j: 0.278, k: 0.618, l: 0.282, m: 0.832,
  n: 0.59, o: 0.602, p: 0.631, q: 0.631, r: 0.432, s: 0.472, t: 0.341, u: 0.59, v: 0.553, w: 0.785, x: 0.565, y: 0.545, z: 0.541,
  A: 0.757, B: 0.695, C: 0.705, D: 0.749, E: 0.619, F: 0.569, G: 0.826, H: 0.808, I: 0.342, J: 0.357, K: 0.739, L: 0.551, M: 0.915,
  N: 0.799, O: 0.83, P: 0.645, Q: 0.885, R: 0.673, S: 0.648, T: 0.59, U: 0.723, V: 0.757, W: 1.087, X: 0.724, Y: 0.689, Z: 0.642,
  ' ': 0.3, '.': 0.329, ',': 0.328, '-': 0.226, '–': 0.796, '?': 0.647, '!': 0.356, "'": 0.313, '’': 0.348, '&': 0.775, '/': 0.636, ':': 0.329,
};
const TRACK = -0.04;

/** 800 で組んだときの幅（em）。「C|mpany」のように o の位置を「|」で書いた語もそのまま渡せる */
export function fit(word: string): number {
  const s = String(word).replace('|', 'o');
  const w = [...s].reduce((t, c) => t + (A[c] ?? 0.62), 0) + s.length * TRACK;
  return Math.round(w * 1.03 * 1000) / 1000;
}

/** style 属性に入れる形 */
export const fitStyle = (word: string) => `--fit:${fit(word)}`;
